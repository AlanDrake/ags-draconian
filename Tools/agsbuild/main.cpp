// The tools' command lines are made of ProcessArgs: every value is one argument, whatever
// characters a path or a game name has.

// A file in a directory, as the tools' command lines name it
static String InDir(const String &dir, const String &file)
{
    return String::FromFormat("%s/%s", dir.GetCStr(), file.GetCStr());
}

ProcessArgs MakeAGSCCFlags(const ScriptCompilerOptions &opts)
{
    ProcessArgs flags{"--override-version",
                      opts.GameCompilerVersion,
                      "-A",
                      opts.ApiVersion,
                      "-C",
                      opts.CompatVersion,
                      String::FromFormat("-fforceobjectbasedscript=%d", opts.EnforcePost262Scripting ? 1 : 0),
                      String::FromFormat("-fforcenewstrings=%d", opts.EnforceNewStrings ? 1 : 0),
                      String::FromFormat("-fforcenewaudio=%d", opts.EnforceNewAudio ? 1 : 0),
                      String::FromFormat("-foldcustomdialogopt=%d", opts.OldDialogOptionsAPI ? 1 : 0)};
    if (!opts.UnicodeMode)
    {
        flags.Add("--ascii");
    }
    if (opts.DebugBuild)
    {
        flags.Add("-g");
    }
    return flags;
}

ProcessArgs MakeSpriteImportFlags(const GameOptions &opts)
{
    int sflags = 0;
    const char *compress;
    switch (opts.SpriteCompression)
    {
    case DataUtil::SpriteCompression::kSprCompress_None: compress = "none"; break;
    case DataUtil::SpriteCompression::kSprCompress_RLE: compress = "rle"; break;
    case DataUtil::SpriteCompression::kSprCompress_LZW: compress = "lzw"; break;
    case DataUtil::SpriteCompression::kSprCompress_Deflate:
    default: compress = "deflate"; break;
    }
    sflags |= 0x1 * opts.SpriteOptimizeStorage;
    return ProcessArgs{"-z", compress, "-s", String::FromFormat("0x%x", sflags)};
}

