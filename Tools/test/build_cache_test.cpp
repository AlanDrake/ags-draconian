void WriteFile(const String &path, const char *text)
{
    std::unique_ptr<Stream> out(File::CreateFile(path));
    ASSERT_TRUE(out != nullptr) << path.GetCStr();
    out->Write(text, strlen(text));
}

String ReadFile(const String &path)
{
    std::unique_ptr<Stream> in(File::OpenFileRead(path));
    return in ? String::FromStream(in.get(), SIZE_MAX) : String();
}

// A fresh folder in the working directory
String MakeTestDir(const char *name)
{
    Directory::DeleteDirectoryTree(name);
    EXPECT_TRUE(Directory::CreateDirectory(name));
    return name;
}

// A project, tools and generated headers as files, and the inputs of room 1 made of them
class RoomCacheTest : public ::testing::Test
{
protected:
    void SetUp() override
    {
        // A folder for each test: ctest runs them at the same time
        const String name =
            String::FromFormat("build_cache_test_%s", ::testing::UnitTest::GetInstance()->current_test_info()->name());
        _dir = MakeTestDir(name.GetCStr());
        ASSERT_TRUE(Directory::CreateAllDirectories(_dir, "Rooms/1"));
        for (const char *tool : {"agsbuild", "agscc", "crmbuild"})
        {
            _in.Tools.push_back(MakeFile(tool, tool));
        }
        _in.GameKeyFile = MakeFile("_RoomGame.key", "1;2;32;65001;");
        for (const char *header :
             {"_BuiltInScriptHeader.ash", "_AutoGenerated.ash", "_GlobalVariables.ash", "__Plugin_a.ash", "Module.ash"})
        {
            _in.Headers.push_back(MakeFile(header, header));
        }
        _in.Commands = {"Game.agf 1 --header", "Rooms/1/room1.asc -o room1/room1.o", "Game.agf 1 -o room1.crm"};
        _in.SourceDir = Path::ConcatPaths(_dir, "Rooms/1");
        MakeFile("Rooms/1/data.xml", "<Room />");
        MakeFile("Rooms/1/background0.png", "background");
        MakeFile("Rooms/1/hotspots.png", "hotspots");
        MakeFile("Rooms/1/room1.asc", "function room_Load() {}");
        _manifest = Manifest();
        ASSERT_FALSE(_manifest.IsEmpty());
    }

    void TearDown() override { Directory::DeleteDirectoryTree(_dir); }

    String MakeFile(const char *name, const char *text)
    {
        const String path = Path::ConcatPaths(_dir, name);
        WriteFile(path, text);
        return path;
    }

    // The manifest of the inputs as they are now; a new hasher, as each build has
    String Manifest()
    {
        FileHasher hasher;
        String manifest;
        HError err = MakeManifest(_in, hasher, manifest);
        EXPECT_TRUE(err) << (err ? "" : err->FullMessage().GetCStr());
        return manifest;
    }

    // A change of the file's contents makes another manifest, and the old contents the same again
    void ExpectContentsCount(const String &path)
    {
        const String old_text = ReadFile(path);
        WriteFile(path, "changed");
        EXPECT_NE(_manifest, Manifest()) << path.GetCStr();
        WriteFile(path, old_text.GetCStr());
        EXPECT_EQ(_manifest, Manifest()) << path.GetCStr();
    }

    String _dir;
    BuildInputs _in;
    String _manifest;
};

