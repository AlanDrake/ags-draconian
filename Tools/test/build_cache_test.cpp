// A build starts with nothing of an earlier one but the rooms it keeps
TEST(RoomCache, ClearTempDirKeepsRoomsWithManifest)
{
    const String dir = MakeTestDir("build_cache_clear_test");
    ASSERT_TRUE(Directory::CreateAllDirectories(dir, "room1"));
    ASSERT_TRUE(Directory::CreateAllDirectories(dir, "room2"));
    ASSERT_TRUE(Directory::CreateAllDirectories(dir, "roomx"));
    ASSERT_TRUE(Directory::CreateAllDirectories(dir, "_voice/speech.vox"));
    WriteFile(Path::ConcatPaths(dir, "room1/manifest.txt"), "manifest");
    WriteFile(Path::ConcatPaths(dir, "room1/room1.o"), "script");
    WriteFile(Path::ConcatPaths(dir, "room1.crm"), "room");
    WriteFile(Path::ConcatPaths(dir, "room2/room2.o"), "script");
    WriteFile(Path::ConcatPaths(dir, "room2.crm"), "room");
    WriteFile(Path::ConcatPaths(dir, "room3.crm"), "room");
    WriteFile(Path::ConcatPaths(dir, "roomx/manifest.txt"), "manifest");
    WriteFile(Path::ConcatPaths(dir, "_voice/speech.vox/a.ogg"), "voice");
    WriteFile(Path::ConcatPaths(dir, "game28.dta"), "data");

    ASSERT_TRUE(ClearTempDirKeepingCache(dir));
    EXPECT_TRUE(File::IsFile(Path::ConcatPaths(dir, "room1/manifest.txt")));
    EXPECT_TRUE(File::IsFile(Path::ConcatPaths(dir, "room1/room1.o")));
    EXPECT_TRUE(File::IsFile(Path::ConcatPaths(dir, "room1.crm")));
    EXPECT_FALSE(File::IsDirectory(Path::ConcatPaths(dir, "room2")));
    EXPECT_FALSE(File::IsFile(Path::ConcatPaths(dir, "room2.crm")));
    EXPECT_FALSE(File::IsFile(Path::ConcatPaths(dir, "room3.crm")));
    EXPECT_FALSE(File::IsDirectory(Path::ConcatPaths(dir, "roomx")));
    EXPECT_FALSE(File::IsDirectory(Path::ConcatPaths(dir, "_voice")));
    EXPECT_FALSE(File::IsFile(Path::ConcatPaths(dir, "game28.dta")));
    Directory::DeleteDirectoryTree(dir);
}

